import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:4310';
const bearer = { Authorization: `Bearer ${process.env.API_TOKEN}` };
assert.equal((await fetch(base)).status, 200);
assert.equal((await fetch(`${base}/events`)).status, 401);
const launch = await fetch(`${base}/workbench/ticket`, { method: 'POST', headers: bearer });
assert.equal(launch.status, 200);
const { ticket } = await launch.json() as { ticket: string };
const signedIn = await fetch(`${base}/session/open?ticket=${ticket}`, { redirect: 'manual' });
assert.equal(signedIn.status, 302);
const setCookie = signedIn.headers.get('set-cookie')!;
assert.match(setCookie, /HttpOnly/); assert.match(setCookie, /SameSite=Strict/);
const cookie = setCookie.split(';')[0];
assert.equal((await fetch(`${base}/session/open?ticket=${ticket}`, { redirect: 'manual' })).status, 401);
assert.equal((await fetch(`${base}/events`, { headers: { Cookie: cookie } })).status, 200);
assert.equal((await fetch(`${base}/connections`, { method: 'POST', headers: { Cookie: cookie, 'Content-Type': 'application/json' }, body: '{}' })).status, 401);
const headers = { Cookie: cookie, 'Content-Type': 'application/json', 'X-DPI-Workbench': '1' };
const saved = await fetch(`${base}/connections`, { method: 'POST', headers, body: JSON.stringify({ name: 'QA reference simulator', target: 'simulator', schema: { sample: 'synthetic' } }) });
assert.equal(saved.status, 200);
const connection: any = await saved.json();
const tested: any = await (await fetch(`${base}/connections/${connection.id}/test`, { method: 'POST', headers, body: '{}' })).json();
assert.equal(tested.ready, true);
assert.equal((await fetch(`${base}/connections`, { method: 'POST', headers, body: JSON.stringify({ name: 'Invalid target', target: 'https://example.com', schema: {} }) })).status, 400);
await fetch(`${base}/session/logout`, { method: 'POST', headers, body: '{}' });
assert.equal((await fetch(`${base}/events`, { headers: { Cookie: cookie } })).status, 401);
console.log('PASS: protected data, one-time launch, session cookie, write-request guard, persistent connection registration, local connectivity test, target restriction, and logout. No Meta request made.');
